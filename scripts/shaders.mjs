// Assemble named, independently editable shader systems for browser and Node tooling.
import { readFileSync, writeFileSync } from 'node:fs';
const systems = ['bindings','geometry','raymarch','compositing','optics','entry'];
const shader = systems.map(name => `// ---- ${name} ----\n${readFileSync(`app/glass/wgsl/${name}.wgsl`, 'utf8')}`).join('\n');
writeFileSync('app/glass/glass.wgsl', '// Generated; edit files in wgsl/.\n' + shader);
writeFileSync('app/glass/shaders.ts', '// Generated by scripts/shaders.mjs.\nexport const glassWgsl = '+JSON.stringify(shader)+';\n');
